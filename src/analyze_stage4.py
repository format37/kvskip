FAMILY_LABEL = {"refresh": "refresh + calibration (stage 4)", "refresh_s3": "refresh + 8 exact heads (stage 3)",
                "quest16": "Quest, 16-token min/max", "quest64": "Quest, 64-token min/max",
                "quest16raw": "Quest-16, raw max over the group", "quest16soft": "Quest-16, softmax sum over the group",
                "quest16rr": "Quest-16, round robin over the group", "quest16native": "Quest, 16-token pages",
                "quest16softnative": "Quest, 16-token pages, softmax sum",
                "static": "static (first step's top blocks)", "topk": "per-step oracle top-k (exact weights)",
                "vskip1": "V-skip, 1 pass (K read in full)"}


def family(name: str) -> tuple[str, float]:
    """(method family, top-p level of the refresh run it is matched to / its own)."""
    lvl = 0.99
    if "_p0." in name:
        lvl = float(name.split("_p")[-1].split("_")[0])
    if name.startswith(("quest", "static", "topk")):
        return name.split("_")[0], lvl                  # quest16, quest64, quest16soft, quest16softnative, ...
    if name.startswith("vprev"):
        return "vskip1", np.nan
    if "_dh8" in name:
        return "refresh_s3", lvl
    return "refresh", lvl


def interp_at(bytes_, kl, target):
    """log-linear interpolation of KL x noise at a byte share (None outside the measured range)."""
    order = np.argsort(bytes_)
    b, k = np.asarray(bytes_)[order], np.log(np.asarray(kl)[order])
    if len(b) < 2 or target < b[0] - 0.01 or target > b[-1] + 0.01:
        return np.nan
    return float(np.exp(np.interp(target, b, k)))


def gmean(x) -> float:
    x = np.asarray(x, dtype=float)
    x = x[np.isfinite(x)]
    return float(np.exp(np.log(x).mean())) if len(x) else np.nan


def budget_tables(grids=("s4q", "s4q2"), budgets=(0.6, 0.5, 0.4, 0.3)):
    """Equal bytes. KL ratios span orders of magnitude and differ by genre, so documents are combined by
    the geometric mean (the worst document next to it) and the operating point is also shown per document."""
    df = summaries(list(grids), model="8b")
    if df.empty:
        return None
    df = df.drop_duplicates(["doc", "ctx", "condition"], keep="first")
    df[["family", "level"]] = [family(n) for n in df.condition]
    save_table(df.set_index(["doc", "family", "level"]).sort_index(), "stage4_budget_by_doc", floatfmt=".3g")
    m = df[~df.family.isin(["vskip1", "refresh_s3"])]
    agg = m.groupby(["level", "family"]).agg(bytes_total=("bytes_total", "mean"), kl_x_noise=("kl_x_noise", gmean),
                                             kl_worst=("kl_x_noise", "max"), top1=("top1", "mean"),
                                             docs=("doc", "count")).reset_index()
    wide = agg.pivot(index="level", columns="family", values="kl_x_noise")
    wide.insert(0, "bytes (refresh run)", agg[agg.family == "refresh"].set_index("level")["bytes_total"])
    save_table(wide.sort_index(ascending=False), "stage4_budget_matched", floatfmt=".3g")
    worst = agg.pivot(index="level", columns="family", values="kl_worst")
    save_table(worst.sort_index(ascending=False), "stage4_budget_matched_worst", floatfmt=".3g")
    op = df[(df.level == 0.99) | df.family.isin(["vskip1", "refresh_s3"])]
    per_doc = op.pivot_table(index="doc", columns="family", values="kl_x_noise", aggfunc="first")
    per_doc.insert(0, "bytes (refresh run)", op[op.family == "refresh"].set_index("doc")["bytes_total"])
    per_doc.loc["geometric mean"] = [per_doc[c].mean() if c == "bytes (refresh run)" else gmean(per_doc[c])
                                     for c in per_doc.columns]
    save_table(per_doc, "stage4_budget_operating", floatfmt=".3g")
    # fixed budgets: interpolated per document on each family's curve, then combined
    rows = []
    for fam in ("refresh", "quest16", "static", "topk"):
        for B in budgets:
            vals = np.array([interp_at(d.bytes_total.values, d.kl_x_noise.values, B)
                             for _, d in df[df.family == fam].groupby("doc")], dtype=float)
            rows.append({"family": fam, "budget": B, "kl_x_noise": gmean(vals),
                         "kl_worst": np.nanmax(vals) if np.isfinite(vals).any() else np.nan,
                         "docs": int(np.isfinite(vals).sum())})
    fixed = pd.DataFrame(rows)
    t = fixed.pivot(index="budget", columns="family", values="kl_x_noise").sort_index(ascending=False)
    t["docs"] = fixed.groupby("budget").docs.min()
    save_table(t, "stage4_budget_fixed", floatfmt=".3g")
    singles = df[df.family.isin(["vskip1", "refresh_s3"])].groupby("family").agg(
        bytes_total=("bytes_total", "mean"), kl_x_noise=("kl_x_noise", gmean), kl_worst=("kl_x_noise", "max"))
    save_table(singles, "stage4_budget_single", floatfmt=".3g")
    # figure: KL vs bytes, per document (thin) and geometric mean (thick)
    fig, axes = plt.subplots(1, 2, figsize=(13, 4.8), gridspec_kw={"width_ratios": [1.25, 1]})
    style = {"refresh": ("o-", "C0"), "quest16": ("s-", "C1"), "quest16softnative": ("s--", "C5"),
             "static": ("^-", "C2"), "topk": ("v:", "C3")}
    ax = axes[0]
    for fam, (mk, col) in style.items():
        d = agg[agg.family == fam].sort_values("bytes_total")
        if d.empty:
            continue
        ax.plot(d.bytes_total, d.kl_x_noise, mk, color=col, label=FAMILY_LABEL.get(fam, fam))
    for fam, mk in (("vskip1", "D"), ("refresh_s3", "*")):
        if fam in singles.index:
            ax.plot(singles.loc[fam, "bytes_total"], singles.loc[fam, "kl_x_noise"], mk, ms=9, label=FAMILY_LABEL[fam])
    ax.axhline(1, color="grey", lw=0.8, ls=":")
    ax.set_yscale("log")
    ax.set_xlabel("K+V bytes per step (blocks + metadata), share of dense")
    ax.set_ylabel("KL / KL of stock bf16 SDPA (geometric mean over documents)")
    ax.set_title(f"Llama-3.1-8B, 32k, {df.doc.nunique()} documents: quality at equal bytes", fontsize=10)
    ax.legend(fontsize=7)
    ax = axes[1]
    for doc, d in df[df.family.isin(["refresh", "quest16softnative", "topk"])].groupby("doc"):
        for fam, (mk, col) in style.items():
            e = d[d.family == fam].sort_values("bytes_total")
            if not e.empty:
                ax.plot(e.bytes_total, e.kl_x_noise, mk, color=col, lw=0.8, ms=3, alpha=0.7)
    ax.set_yscale("log")
    ax.axhline(1, color="grey", lw=0.8, ls=":")
    ax.set_xlabel("K+V bytes per step, share of dense")
    ax.set_title("per document: refresh (blue), Quest 16-token pages (brown), oracle (red)", fontsize=9)
    fig.tight_layout()
    save_fig(fig, "stage4_budget")
    return df


