def calib_main(df: pd.DataFrame):
    """Headline table: key variants x (model, document set): mean KL x noise (worst document),
    bytes and refresh rate."""
    d = df[df.condition.isin(KEY_VARIANTS)].copy()
    if d.empty:
        return None
    d["model_set"] = [f"{MODEL_NAMES[m]}: {s}" for m, s in zip(d.model, d.set)]
    agg = d.groupby(["condition", "model_set"]).agg(kl=("kl_x_noise", "mean"), worst=("kl_x_noise", "max"),
                                                    bytes=("bytes_total", "mean"), refresh=("refresh_rate", "mean"),
                                                    docs=("doc", "count")).reset_index()
    agg["variant"] = agg.condition.map(KEY_VARIANTS)
    cell = agg.assign(cell=[f"{k:.2f} ({w:.1f})" for k, w in zip(agg.kl, agg.worst)])
    order = [v for v in KEY_VARIANTS.values() if v in set(agg.variant)]
    t = cell.pivot(index="variant", columns="model_set", values="cell").reindex(order)
    save_table(t, "stage4_calib_main", floatfmt=".3g")
    tb = agg.pivot(index="variant", columns="model_set", values="bytes").reindex(order)
    save_table(tb, "stage4_calib_main_bytes", floatfmt=".3f")
    tr = agg.pivot(index="variant", columns="model_set", values="refresh").reindex(order)
    save_table(tr, "stage4_calib_main_refresh", floatfmt=".3f")
    # figure: mean KL x noise per variant and set (log), the variants that tell the story
    set_order = [f"{MODEL_NAMES[m]}: {s_}" for m, s_ in (
        ("8b", "stage-1 docs 16k"), ("8b", "stage-1 docs 32k"), ("8b", "held-out (a4) 32k"), ("8b", "held-out (s3) 32k"),
        ("qwen3-8b", "stage-1 docs 16k"), ("qwen3-8b", "stage-1 docs 32k"))]
    sets = [c for c in set_order if c in t.columns]
    show = ["trigger alone (no list, delta 0.05)", "+ 8 always-exact heads (stage 3, Llama)",
            "trigger alone, delta 0.02 (stage 3, Qwen3)", "ratio correction, EMA 0.3 (kickoff)",
            "peak-hold correction, no warm-up", "peak-hold + warm-up + auto token index (stage 4)"]
    order = [v for v in show if v in order]
    fig, ax = plt.subplots(figsize=(11, 4.4))
    w = 0.8 / max(1, len(order))
    x = np.arange(len(sets))
    for i, v in enumerate(order):
        vals = [agg[(agg.variant == v) & (agg.model_set == s)].kl.mean() for s in sets]
        ax.bar(x + i * w, vals, w, label=v)
    ax.axhline(1, color="grey", lw=0.8, ls=":")
    ax.set_yscale("log")
    ax.set_xticks(x + 0.4 - w / 2, [s.replace(": ", "\n") for s in sets], fontsize=8)
    ax.set_ylabel("KL / KL of stock bf16 SDPA")
    ax.set_title("Refresh trigger without hand parameters (mean over 3 documents per group, log scale)", fontsize=10)
    ax.legend(fontsize=7.5, ncol=2, loc="upper right")
    fig.tight_layout()
    save_fig(fig, "stage4_calib")
    return t


def calib_heads(model: str, condition: str, grids=("s4b", "s4c")):
    """Which heads the calibration singles out: the correction at the end of the run and the
    share of steps a head refreshed, against the induction diagnostic (attention on the token
    after an earlier copy of the current token, m_after) of the same run."""
    frames = []
    for grid in grids:
        for f in sorted(REUSE.glob(f"{model}_*.{grid}.heads.parquet")):
            h = pd.read_parquet(f, filters=[("condition", "==", condition)])
            if h.empty:
                continue
            h = h[h.layer.isin(h.layer[h.refresh < 1].unique())]          # sparse layers
            frames.append(h.assign(doc=f.name.split(".")[0]))
    if not frames:
        return None
    h = pd.concat(frames)
    last = h[h.step >= h.step.max() - 31]
    per = h.groupby(["layer", "kv_head"]).agg(refresh_rate=("refresh", "mean"), m_after=("m_after", "mean"),
                                             m_same=("m_same", "mean"), cov_min=("covered_min", "mean"),
                                             on_index=("auto_ix", "mean"))
    last_step = h[h.step == h.step.max()]
    per["docs_latched"] = last_step.groupby(["layer", "kv_head"]).auto_ix.sum()
    per["calib_last32"] = last.groupby(["layer", "kv_head"]).calib.mean()
    per["calib_max"] = h.groupby(["layer", "kv_head"]).calib.max()
    per["docs_calib_gt_0.05"] = h[h.step == h.step.max()].assign(hi=lambda d: d.calib > 0.05).groupby(
        ["layer", "kv_head"]).hi.sum()
    per["stage2_exact"] = [(l, k) in DENSE_HEADS_8B for l, k in per.index] if model == "8b" else False
    per = per.sort_values("calib_last32", ascending=False)
    save_table(per.head(24), f"stage4_calib_heads_{model}", floatfmt=".3f")
    top_c = set(per.head(8).index)
    top_ind = set(per.sort_values("m_after", ascending=False).head(8).index)
    latched = per[per.docs_latched > 0].sort_values(["docs_latched", "m_after"], ascending=False)
    save_table(latched, f"stage4_latched_{model}", floatfmt=".3f")
    ind_rank = per["m_after"].rank(ascending=False)
    rank = per[["calib_last32", "m_after"]].rank()
    out = {"model": model, "condition": condition, "top8_calib": sorted(top_c), "top8_induction": sorted(top_ind),
           "overlap_top8": len(top_c & top_ind),
           "spearman_calib_vs_induction": float(rank.corr().iloc[0, 1]),
           "stage2_exact_in_top8_calib": int(sum(per.loc[list(top_c), "stage2_exact"])) if model == "8b" else None,
           "latched_heads": len(latched), "latched_in_top8_induction": int(sum(i in top_ind for i in latched.index)),
           "latched_median_induction_rank": float(ind_rank.loc[latched.index].median()) if len(latched) else None,
           "docs": int(h.doc.nunique())}
    return per, out


