def summaries(grids, model=None) -> pd.DataFrame:
    """One row per (model, doc, ctx, grid, condition) from the probe runs' summary.json."""
    rows = []
    for grid in grids:
        for f in sorted(REUSE.glob(f"*.{grid}.summary.json")):
            r = json.loads(f.read_text())
            if model and r["model"] != model:
                continue
            for name, c in r["conditions"].items():
                rows.append({"model": r["model"], "doc": r["genre"], "ctx": r["ctx"], "grid": grid, "condition": name,
                             "noise_kl": r["noise_kl_mean"], "kl_x_noise": c["kl_x_noise"],
                             "kl_p95_x_noise": c["kl_p95_x_noise"], "top1": c["top1_agree"],
                             "k_skip": c["k_skip"], "v_skip": c["v_skip"], "refresh_rate": c["refresh_rate"],
                             "bytes_total": c.get("bytes_total", np.nan), "bytes_blocks": c.get("bytes_blocks", np.nan),
                             "bytes_meta": c.get("bytes_meta", np.nan), "match": c.get("match"),
                             "calib_heads_gt1": c.get("calib_heads_gt1", np.nan)})
    return pd.DataFrame(rows)


def doc_set(doc: str, ctx: int) -> str:
    if doc in STAGE1_DOCS:
        return f"stage-1 docs {ctx // 1024}k"
    if doc in HELDOUT_A4:
        return f"held-out (a4) {ctx // 1024}k"
    return f"held-out (s3) {ctx // 1024}k"


