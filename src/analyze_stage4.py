def calib_tables(grids=("s4a", "s4b", "s4c")):
    df = summaries(grids)
    if df.empty:
        return None
    df = df.drop_duplicates(["model", "doc", "ctx", "condition"], keep="last")
    df["set"] = [doc_set(d, c) for d, c in zip(df.doc, df.ctx)]
    save_table(df.set_index(["model", "set", "condition", "doc"]).sort_index(), "stage4_calib_by_doc", floatfmt=".3g")
    agg = df.groupby(["model", "set", "condition"]).agg(
        kl_x_noise=("kl_x_noise", "mean"), kl_worst=("kl_x_noise", "max"), top1=("top1", "mean"),
        skip=("k_skip", "mean"), bytes_total=("bytes_total", "mean"), refresh_rate=("refresh_rate", "mean"),
        docs=("doc", "count"))
    save_table(agg, "stage4_calib", floatfmt=".3g")
    return df


