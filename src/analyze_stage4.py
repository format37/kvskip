def gate_table(tag="s4"):
    rows = []
    for f in sorted((RES / "lab").glob(f"{tag}_*.json")):
        r = json.loads(f.read_text())
        for m, per in r["step_ms"].items():
            for B, t in per.items():
                dense = r["step_ms"]["dense"][B]
                b = r["bytes"].get(m, {})
                rows.append({"ctx": r["ctx"], "bs": int(B), "mode": m, "ms_per_step": t, "gain_vs_dense": 1 - t / dense,
                             "kl_x_noise": r["kl"].get(m, {}).get("x_noise", np.nan),
                             "kv_read_sparse": b.get("kv_read_frac_sparse_layers", np.nan),
                             "refresh_rate": b.get("refresh_rate", np.nan)})
    if not rows:
        return None
    df = pd.DataFrame(rows)
    save_table(df.set_index(["ctx", "bs", "mode"]).sort_index(), "stage4_gate", floatfmt=".3f")
    return df


def gate_summary(tag="s4", mode="refresh_cal", points=((32768, 8), (32768, 32), (65536, 8), (65536, 32))):
    """README table: per (ctx, bs) the K+V share read in the whole step (layer 0 dense), attention time and
    step time (HF eager) dense -> policy, and the policy's KL x noise (teacher-forced, 8 documents)."""
    rows = []
    labs = {json.loads(f.read_text())["ctx"]: json.loads(f.read_text()) for f in sorted((RES / "lab").glob(f"{tag}_*.json"))}
    for ctx, B in points:
        r = labs.get(ctx)
        if r is None or mode not in r["step_ms"]:
            continue
        Bs = str(B)
        L = 32
        b = r["bytes"].get(mode, {})
        kv_read = 1 - (L - 1) / L * (1 - b.get("kv_read_frac_sparse_layers", 1.0))
        a0, a1 = r["attn_ms"]["dense"][Bs], r["attn_ms"][mode][Bs]
        t0, t1 = r["step_ms"]["dense"][Bs], r["step_ms"][mode][Bs]
        row = {"ctx": ctx, "bs": B, "kv_read": kv_read, "attn_dense_ms": a0, "attn_ms": a1, "attn_gain": 1 - a1 / a0,
               "step_dense_ms": t0, "step_ms": t1, "step_gain": 1 - t1 / t0,
               "kl_x_noise": r["kl"].get(mode, {}).get("x_noise", np.nan),
               "refresh_rate": b.get("refresh_rate", np.nan)}
        for other in ("refresh_fused", "vskip1"):
            if other in r["step_ms"]:
                row[f"step_gain_{other}"] = 1 - r["step_ms"][other][Bs] / t0
                row[f"kl_{other}"] = r["kl"].get(other, {}).get("x_noise", np.nan)
        rows.append(row)
    if not rows:
        return None
    df = pd.DataFrame(rows).set_index(["ctx", "bs"])
    save_table(df, "stage4_gate_summary", floatfmt=".3g")
    return df


