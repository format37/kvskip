def model_map(models=("8b", "qwen3-8b", "qwen2.5-7b", "mistral-7b"), ctx=32768):
    """Per model: blocks for 0.99 of the mass, layer 0, the densest layers, sink, block 0 and the
    newest blocks (stage-1 collect + the diag run's records), jumps, timer vs trigger."""
    rows, per_layer = [], []
    for model in models:
        ks = sorted((RES / "collect").glob(f"{model}_*_{ctx}.kv.parquet"))
        hs = sorted((RES / "collect").glob(f"{model}_*_{ctx}.heads.parquet"))
        if not ks:
            continue
        k = pd.concat([pd.read_parquet(f, columns=["layer", "union_frac_blocks_to_0.99"]) for f in ks])
        h = pd.concat([pd.read_parquet(f, columns=["layer", "sink_mass", "frac_blocks_to_0.99"]) for f in hs])
        L = int(k.layer.max()) + 1
        ul = k.groupby("layer")["union_frac_blocks_to_0.99"].mean()
        sl = h.groupby("layer")["sink_mass"].median()
        dense = ul.sort_values(ascending=False)
        row = {"model": MODEL_NAMES[model], "layers": L,
               "kv_blocks_0.99_layers_gt0": float(k[k.layer > 0]["union_frac_blocks_to_0.99"].mean()),
               "q_blocks_0.99_layers_gt0": float(h[h.layer > 0]["frac_blocks_to_0.99"].mean()),
               "layer0_kv_blocks_0.99": float(ul.loc[0]),
               "densest_layers": ",".join(str(int(x)) for x in sorted(dense.index[:3])),
               "densest_share": float(dense.iloc[:3].mean()),
               "sink_mass_median_over_layers": float(sl.median()),
               "layers_without_sink": int((sl < 0.01).sum())}
        mass = None                                   # block-0 / newest-block mass: any run that recorded it
        for grid in ("diag", "s4a", "s4b", "s4p"):
            fs = sorted(REUSE.glob(f"{model}_*_{ctx}.{grid}.heads.parquet"))
            if fs and "m_sink" in pd.read_parquet(fs[0]).columns:
                mass = pd.concat([pd.read_parquet(f, columns=["condition", "layer", "m_sink", "m_local"]) for f in fs])
                break
        if mass is not None:
            first = mass[mass.condition == mass.condition.iloc[0]]
            row["block0_mass_mean"] = float(first.groupby("layer").m_sink.mean().mean())
            row["last2_blocks_mass_mean"] = float(first.groupby("layer").m_local.mean().mean())
        diag = sorted(REUSE.glob(f"{model}_*_{ctx}.diag.heads.parquet"))
        jl = []
        for f in diag:
            t = pd.read_parquet(f, columns=["condition", "step", "layer", "kv_head", "covered_stale_min"])
            t = t[(t.condition == "timer_N32") & (t.layer > 0)]
            if t.empty:
                continue
            lost = t.assign(lost=t.covered_stale_min < 0.95).pivot_table(
                index="step", columns=["layer", "kv_head"], values="lost").astype(bool)
            steps = [i for i in range(2, len(lost)) if lost.index[i] % 32 >= 2]
            newly = np.array([int((lost.iloc[i] & ~lost.iloc[i - 1]).sum()) for i in steps])
            jl.append((newly.max(), np.median(newly), lost.shape[1]))
        if jl:
            row["jump_max_heads"] = int(max(j[0] for j in jl))
            row["jump_median_heads"] = float(np.median([j[1] for j in jl]))
            row["sparse_kv_heads"] = int(jl[0][2])
        sm = summaries(["diag", "s4a", "s4b", "s4p"], model=model)
        sm = sm[(sm.ctx == ctx) & sm.doc.isin(STAGE1_DOCS)].drop_duplicates(["doc", "condition"], keep="last")
        for cond, key in (("timer_N32", "kl_timer32"), ("fresh", "kl_fresh"), ("estp_delta0.05_age32", "kl_trigger"),
                          ("estp_delta0.02_age32", "kl_trigger_d0.02"), (FINAL, "kl_stage4")):
            d = sm[sm.condition == cond]
            if not d.empty:
                row[key] = float(d.kl_x_noise.mean())
                row[key + "_worst"] = float(d.kl_x_noise.max())
                if cond in ("estp_delta0.05_age32", FINAL):
                    row[key + "_bytes"] = float(d.bytes_total.mean()) if d.bytes_total.notna().any() else np.nan
        rows.append(row)
        t = pd.DataFrame({"kv_blocks_0.99": ul, "sink_mass_median": sl})
        t["model"], t["depth"] = MODEL_NAMES[model], t.index / (L - 1)
        per_layer.append(t.reset_index())
    if not rows:
        return None
    df = pd.DataFrame(rows).set_index("model")
    shown = df.T.apply(lambda col: [f"{v:.3g}" if isinstance(v, float) else v for v in col])
    save_table(shown, "stage4_models", floatfmt=".3g")
    pl = pd.concat(per_layer)
    fig, axes = plt.subplots(1, 2, figsize=(12, 4.2))
    for name, d in pl.groupby("model", sort=False):
        axes[0].plot(d.depth, d["kv_blocks_0.99"], ".-", label=name)
        axes[1].plot(d.depth, d["sink_mass_median"], ".-", label=name)
    axes[0].set_title(f"KV-head blocks for 0.99 of the mass (GQA union), {ctx // 1024}k", fontsize=10)
    axes[1].set_title("attention on the first 4 tokens (median head)", fontsize=10)
    for ax in axes:
        ax.set_xlabel("layer / (layers - 1)")
