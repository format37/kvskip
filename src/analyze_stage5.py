CARRY_LABEL = {"": "stage 4: every document from zero", "_carry0.5": "carry c x 0.5",
               "_carry0.8": "carry c x 0.8", "_carry1": "carry c x 1",
               "_carry1_cw0": "carry c x 1, no warm-up once carried", "_latchcarry1": "carry the index latch only",
               "_floor0.8": "floor: worst miss so far, x 0.8 per document"}


def carry_label(name: str) -> str:
    return CARRY_LABEL.get(name[len(FINAL):], name)


def carry_frames(model: str, ctx=32768):
    docs, heads, steps = [], [], []
    for order in ("fwd", "rev"):
        p = RES / "carry" / f"{model}_{ctx}_{order}.json"
        if not p.exists():
            continue
        r = json.loads(p.read_text())
        for d in r["docs"]:
            for name, c in d["conditions"].items():
                docs.append({"order": order, "position": d["position"], "doc": d["doc"], "condition": name,
                             "variant": carry_label(name), **c})
        heads.append(pd.read_parquet(RES / "carry" / f"{model}_{ctx}_{order}.heads.parquet"))
        steps.append(pd.read_parquet(RES / "carry" / f"{model}_{ctx}_{order}.steps.parquet"))
    if not docs:
        return None
    return pd.DataFrame(docs), pd.concat(heads), pd.concat(steps)


def carry_tables(model: str):
    fr = carry_frames(model)
    if fr is None:
        return None
    d, h, s = fr
    order = [v for v in CARRY_LABEL.values() if v in set(d.variant)]
    base = d[d.condition == FINAL].set_index(["order", "doc"])
    d["d_bytes"] = [r.bytes_total - base.loc[(r.order, r.doc), "bytes_total"] for r in d.itertuples()]
    summ = d.groupby(["variant", "order"]).agg(kl_mean=("kl_x_noise", "mean"), kl_gmean=("kl_x_noise", gmean),
                                               kl_worst=("kl_x_noise", "max"), bytes=("bytes_total", "mean"),
                                               d_bytes_pp=("d_bytes", lambda x: 100 * x.mean()),
                                               refresh=("refresh_rate", "mean"), worst_step=("worst_step_x_noise", "max"),
                                               latched_start=("latched_start", "mean")).reset_index()
    summ["variant"] = pd.Categorical(summ.variant, order)
    summ = summ.sort_values(["order", "variant"]).set_index(["order", "variant"])
    save_table(summ, f"stage5_carry_{model}", floatfmt=".3g")
    t = d.pivot_table(index=["order", "position", "doc"], columns="variant", values="kl_x_noise")[order]
    save_table(t, f"stage5_carry_{model}_by_doc", floatfmt=".3g")
    w = d.assign(cell=[f"{a:.0f} @{b}" for a, b in zip(d.worst_step_x_noise, d.worst_step)]).pivot_table(
        index=["order", "position", "doc"], columns="variant", values="cell", aggfunc="first")[order]
    save_table(w, f"stage5_carry_{model}_worst_step")
    return d, h, s, summ


def carry_summary(d, model: str):
    """Per variant over the (document, order) pairs after each chain's first document (where every variant
    equals stage 4): mean KL x noise, the same without each document's 3 worst steps, pairs with a step above
    x50, pairs better / worse than stage 4 by 10%, extra bytes (mean, max)."""
    d = d[d.position > 1].copy()
    base = d[d.condition == FINAL].set_index(["order", "doc"])
    d["ratio"] = [r.kl_x_noise / base.loc[(r.order, r.doc), "kl_x_noise"] for r in d.itertuples()]
    d["d_bytes"] = [100 * (r.bytes_total - base.loc[(r.order, r.doc), "bytes_total"]) for r in d.itertuples()]
    t = d.groupby("variant").agg(pairs=("kl_x_noise", "count"), kl_mean=("kl_x_noise", "mean"),
                                 kl_wo_worst3=("kl_x_noise_wo_worst3", "mean"),
                                 pairs_step_gt_50=("worst_step_x_noise", lambda x: int((x > 50).sum())),
                                 better=("ratio", lambda x: int((x < 0.9).sum())), worse=("ratio", lambda x: int((x > 1.1).sum())),
                                 d_bytes_pp=("d_bytes", "mean"), d_bytes_pp_max=("d_bytes", "max"))
    t = t.reindex([v for v in CARRY_LABEL.values() if v in t.index])
    save_table(t, f"stage5_carry_summary_{model}", floatfmt=".3g")
    return t


def offender(d, h, model="8b", doc="code", head=(5, 2)):
    """The rare offender in the carried runs: KL on its document, its worst step, the head's coverage and state."""
    rows = []
    for (order, cond), g in d[d.doc == doc].groupby(["order", "condition"]):
        hh = h[(h.order == order) & (h.condition == cond) & (h.doc == doc) & (h.layer == head[0]) & (h.kv_head == head[1])]
        prev = h[(h.order == order) & (h.condition == cond) & (h.position < g.position.iloc[0]) &
                 (h.layer == head[0]) & (h.kv_head == head[1])]
        rows.append({"order": order, "variant": carry_label(cond), "position": int(g.position.iloc[0]),
                     "kl_x_noise": float(g.kl_x_noise.iloc[0]), "worst_step": int(g.worst_step.iloc[0]),
                     "worst_step_x_noise": float(g.worst_step_x_noise.iloc[0]),
                     "head_covered_min": float(hh.covered_min.iloc[0]) if len(hh) else np.nan,
                     "head_refresh_rate": float(hh.refresh_rate.iloc[0]) if len(hh) else np.nan,
                     "head_latched": bool(hh.latched.iloc[0]) if len(hh) else None,
                     "head_peak_before": float(prev.c_peak.max()) if len(prev) else np.nan,
                     "bytes": float(g.bytes_total.iloc[0])})
    t = pd.DataFrame(rows).set_index(["order", "variant"])
    save_table(t, f"stage5_carry_offender_{model}_{doc}", floatfmt=".3g")
    return t


def carry_trace(model="8b", doc="code", head=(5, 2), step=62):
    """Head (5, 2) step by step on code after prose (run_carry --trace): does the carried correction make the
    head refresh at its bad step, or does it move an earlier refresh?"""
    p = RES / "carry" / f"{model}_32768_fwd_trace.trace.parquet"
    if not p.exists():
        return None
    t = pd.read_parquet(p)
    t = t[(t.doc == doc) & (t.layer == head[0]) & (t.kv_head == head[1])]
    rows = []
    for cond, g in t.groupby("condition", sort=False):
        g = g.set_index("step").sort_index()
        before = g[(g.index < step - 1) & (g.refresh > 0)].index
        rows.append({"variant": carry_label(cond), "c_at_step0": float(g.calib.iloc[0]),
                     "last_refresh_before": int(before.max()), "refresh_at_bad_steps": int(g.loc[[step - 1, step], "refresh"].sum()),
                     "coverage_prev": float(g.loc[step - 1, "covered_min"]), "coverage": float(g.loc[step, "covered_min"]),
                     "estimate_plus_c": float(g.loc[step, "miss_p"] + max(g.loc[step, "calib"], g.loc[step, "floor"])),
                     "kl_x_noise_at_step": float(g.loc[step, "kl_x_noise"]), "refresh_rate": float(g.refresh.iloc[1:].mean())})
    tb = pd.DataFrame(rows).set_index("variant")
    save_table(tb, f"stage5_carry_trace_{model}", floatfmt=".3g")
    return tb


def carried_heads(d, h, model="8b", ref=DENSE_HEADS_8B):
    """2.2: which heads the carried state singles out after the last document, against stage 3's list."""
    rows = []
    for (order, cond), g in h.groupby(["order", "condition"]):
        last = g[g.position == g.position.max()]
        hi = set(map(tuple, last[last.c_eff_end > 0.1][["layer", "kv_head"]].values))
        latched = set(map(tuple, last[last.latched][["layer", "kv_head"]].values))
        ever = set(map(tuple, g[g.c_peak > 0.1][["layer", "kv_head"]].values))
        rows.append({"order": order, "variant": carry_label(cond), "c_gt_0.1_after_last": len(hi),
                     "of_stage3_list": len(hi & set(ref)), "latched_after_last": len(latched),
                     "latched_of_stage3_list": len(latched & set(ref)), "peak_gt_0.1_any_doc": len(ever),
                     "peak_of_stage3_list": len(ever & set(ref)),
                     "stage3_heads_never_peaking": ",".join(f"{l}.{k}" for l, k in sorted(set(ref) - ever))})
    t = pd.DataFrame(rows).set_index(["order", "variant"])
    save_table(t, f"stage5_carry_heads_{model}", floatfmt=".3g")
    # how often each head peaks above 0.1 over the documents (no-carry runs: the heads' own behaviour)
    g = h[(h.condition == FINAL) & (h.order == "fwd")]
    freq = g.assign(hi=g.c_peak > 0.1).groupby(["layer", "kv_head"]).agg(
        docs_peak_gt_0_1=("hi", "sum"), peak_max=("c_peak", "max"), covered_min=("covered_min", "min"))
    freq["stage3_list"] = [(l, k) in ref for l, k in freq.index]
    save_table(freq.sort_values(["docs_peak_gt_0_1", "peak_max"], ascending=False).head(30),
               f"stage5_carry_head_freq_{model}", floatfmt=".3g")
    return t, freq


def online_signal(ref=DENSE_HEADS_8B):
    """2.2 offline: is stage 3's list visible in what the calibration can see -- the policy's own refresh samples
    (real vs estimated miss of the stale set) on the 9 Llama documents of stage 4 (32k, the stage-4 policy)?
    Stage 3 ranked heads by the rate of invisible losses (stale set covers < 0.95, estimate < 0.02) of
    32-step-old sets on every step (src/calibrate_heads.py); here the same event is counted on refresh samples."""
    runs = [(d, "s4p") for d in ("prose", "code", "dialog")] + [(d, "s4b") for d in ("prose2", "code2", "dialog2")] + \
           [(d, "s4c") for d in ("prose3", "code3", "dialog3")]
    frames = []
    for doc, grid in runs:
        p = RES / "reuse" / f"8b_{doc}_32768.{grid}.heads.parquet"
        if not p.exists():
            return None
        h = pd.read_parquet(p, filters=[("condition", "==", FINAL)],
                            columns=["step", "layer", "kv_head", "refresh", "covered_stale_min", "miss_p", "covered_min"])
        frames.append(h[(h.layer > 0) & (h.step > 0)].assign(doc=doc))
    h = pd.concat(frames)
    r = h[h.refresh > 0].assign(real=lambda d: 1 - d.covered_stale_min)
    r = r.assign(resid=r.real - r.miss_p, inv=(r.real > 0.05) & (r.miss_p < 0.02))
    per = r.groupby(["layer", "kv_head"]).agg(refresh_samples=("inv", "size"), invisible=("inv", "sum"),
                                              invisible_rate=("inv", "mean"), worst_residual=("resid", "max"))
    per["docs_with_invisible"] = r[r.inv].groupby(["layer", "kv_head"]).doc.nunique()
    nr = h[h.refresh == 0]
    per["missed_steps_cov_lt_0.8"] = nr.assign(b=nr.covered_min < 0.8).groupby(["layer", "kv_head"]).b.sum()
    per = per.fillna(0)
    per["stage3_list"] = [(l, k) in ref for l, k in per.index]
    top = per.sort_values(["invisible_rate", "invisible"], ascending=False)
    save_table(pd.concat([top.head(12), per[per.stage3_list & ~per.index.isin(top.head(12).index)]]),
               "stage5_online_signal_8b", floatfmt=".3g")
    overlap = {k: len(set(per.sort_values(k, ascending=False).head(8).index) & set(ref))
               for k in ("invisible_rate", "invisible", "worst_residual", "missed_steps_cov_lt_0.8")}
    return per, overlap


def carry_figure(models=("8b", "qwen3-8b")):
    frames = {m: carry_frames(m) for m in models}
    panels = [(m, o) for m in models if frames[m] is not None for o in ("fwd", "rev")
              if (frames[m][0].order == o).any()]
    if not panels:
        return
    fig, axes = plt.subplots(1, len(panels), figsize=(4.6 * len(panels), 4.4), squeeze=False)
    show = ["stage 4: every document from zero", "carry c x 1", "carry the index latch only",
            "floor: worst miss so far, x 0.8 per document", "carry c x 1, no warm-up once carried"]
    for ax, (m, o) in zip(axes[0], panels):
        d = frames[m][0]
        d = d[d.order == o]
        base = d[d.condition == FINAL].set_index("doc").bytes_total
        for i, v in enumerate(show):
            e = d[d.variant == v].sort_values("position")
            if not e.empty:
                extra = 100 * float((e.set_index("doc").bytes_total - base).mean())
                ax.plot(e.position, e.kl_x_noise, "o-", ms=3.5, lw=1.2, color=f"C{i}",
                        label=v + ("" if v.startswith("stage 4") else f" ({extra:+.1f} p.p. bytes)"))
        ax.axhspan(*NOISE_BAND, color="grey", alpha=0.15, lw=0)
        ax.set_ylim(0.5, max(3.0, float(d.kl_x_noise.max()) * 1.05))
        docs = d.drop_duplicates("position").sort_values("position").doc.tolist()
        ax.set_xticks(range(1, len(docs) + 1), docs, rotation=60, fontsize=7)
        ax.set_title(f"{MODEL_NAMES[m]}, 32k, {'forward' if o == 'fwd' else 'reverse'} order", fontsize=9)
    axes[0][0].set_ylabel("KL / KL of stock bf16 SDPA (document)")
    for i, (ax, (m, o)) in enumerate(zip(axes[0], panels)):
        if i == 0 or panels[i - 1][0] != m:                       # one legend per model: its own byte costs
            ax.legend(fontsize=6.5, loc="upper left")
    fig.tight_layout()
    save_fig(fig, "stage5_carry")


