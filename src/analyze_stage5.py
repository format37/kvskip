def short(name: str) -> str:
    """A readable label for a condition of the passkey / budget runs."""
    if name.startswith("questp"):
        return f"Quest as published, {name[6:]} tokens / query head"
    if name == FINAL:
        return "refresh + calibration (stage 4), top-p 0.99"
    if name.startswith("estp") and "_p0." in name:
        return f"refresh + calibration, top-p {name.split('_p')[-1]}"
    if name.startswith("topk_match-"):
        return f"per-step oracle at the bytes of {name.split('match-')[1][:10]}"
    if name.startswith("static_match-"):
        return f"static at the bytes of {name.split('match-')[1][:10]}"
    if name.startswith("quest16softnative_match-"):
        return f"Quest, stage-4 GQA variant, at the bytes of {name.split('match-')[1][:10]}"
    return name


def passkey_table(model="8b", ctx=32768):
    p = RES / "passkey" / f"{model}_{ctx}.json"
    if not p.exists():
        return None
    runs = json.loads(p.read_text())["runs"]
    rows = [{"condition": "exact fp32 (reference)", "retrieved": sum(r["ref_retrieved"] for r in runs),
             "depths": len(runs), "kl_x_noise": np.nan, "kl_worst": np.nan, "answer_kl_x_noise": np.nan,
             "bytes_total": 1.0}]
    names = list(runs[0]["conditions"])
    for n in names:
        cs = [r["conditions"][n] for r in runs if n in r["conditions"]]
        rows.append({"condition": short(n), "retrieved": sum(c["retrieved"] for c in cs), "depths": len(cs),
                     "kl_x_noise": gmean([c["kl_x_noise"] for c in cs]), "kl_worst": max(c["kl_x_noise"] for c in cs),
                     "answer_kl_x_noise": gmean([c["kl_answer_x_noise"] for c in cs]),
                     "answer_as_reference": sum(c["answer_same"] for c in cs),
                     "bytes_total": float(np.mean([c["bytes_total"] for c in cs])), "name": n})
    t = pd.DataFrame(rows).set_index("condition")
    save_table(t.drop(columns="name"), "stage5_passkey", floatfmt=".3g")
    by_depth = pd.DataFrame({f"{r['depth']}%": {**{"pass key": r["pass_key"], "reference": r["ref_answer"].strip()},
                                                **{short(n): ("ok " if c["retrieved"] else "MISS ") + repr(c["answer"].strip()[:18])
                                                   for n, c in r["conditions"].items()}} for r in runs})
    save_table(by_depth, "stage5_passkey_by_depth")
    return t


def passkey_diag(model="8b", ctx=32768):
    """The policy's single-step spikes on the passkey: per depth, KL x noise of the stage-4 policy, of the stage-3
    list and of the policy with (2, 5) on the token index from step 0; the worst step and the worst-covered head."""
    p = RES / "passkey" / f"{model}_{ctx}_diag.json"
    if not p.exists():
        return None
    runs = {r["depth"]: r for r in json.loads(p.read_text())["runs"]}
    latch = RES / "passkey" / f"{model}_{ctx}_latch25.json"
    latch = {r["depth"]: r for r in json.loads(latch.read_text())["runs"]} if latch.exists() else {}
    h = pd.read_parquet(RES / "passkey" / f"{model}_{ctx}_diag.heads.parquet")
    rows = []
    for depth, r in sorted(runs.items()):
        g = h[(h.depth == depth) & (h.condition == FINAL) & (h.layer > 0)]
        worst = int(g.groupby("step").kl.first().idxmax())
        w = g[g.step == worst].sort_values("covered_min").iloc[0]
        row = {"depth": depth, "stage4_kl_x_noise": r["conditions"][FINAL]["kl_x_noise"],
               "stage3_list_kl_x_noise": r["conditions"]["estp_delta0.05_age32_dh8"]["kl_x_noise"],
               "worst_step": worst, "answer_token": worst - (r["question_tokens"] - 1),
               "head": f"({int(w.layer)}, {int(w.kv_head)})", "head_coverage": float(w.covered_min),
               "head_estimate": float(w.miss_p), "head_correction": float(w.calib), "head_on_index": bool(w.auto_ix),
               "index_coverage": float(w.idx_cov)}
        if depth in latch:
            row["stage4_with_2.5_on_index_kl_x_noise"] = next(iter(latch[depth]["conditions"].values()))["kl_x_noise"]
        rows.append(row)
    t = pd.DataFrame(rows).set_index("depth")
    save_table(t, "stage5_passkey_spikes", floatfmt=".3g")
    return t


def classify(name: str):
    """(family, point) of a budget-run condition; the point names the budget the condition is set to."""
    lvl = name.split("_p")[-1].split("_")[0] if "_p0." in name else "0.99"
    if name.startswith("questp"):
        return "questp", int(name[6:].split("_")[0])
    if name.startswith(("topk_match-", "static_match-", "quest")):
        fam = name.split("_")[0]
        fam = {"quest16softnative": "quest_s4best", "quest16": "quest_s4kickoff"}.get(fam, fam)
        target = name.split("match-")[1] if "match-" in name else name
        point = target if target.startswith("questp") else f"p{lvl}"
        return fam, point
    if name.startswith("vprev"):
        return "vskip1", "-"
    if "_dh8" in name:
        return "refresh_s3", "p0.99"
    if name.startswith("estp") and "cal0.05" in name:
        return "refresh", f"p{lvl}"
    return "other", name


def budget_points(grids=("s4q", "s5q")):
    df = summaries(list(grids), model="8b")
    if df.empty:
        return None
    df = df[(df.ctx == 32768) & df.doc.isin(BUDGET_DOCS)]
    df = df.drop_duplicates(["doc", "condition"], keep="last")
    df[["family", "point"]] = [classify(n) for n in df.condition]
    df["point"] = df.point.astype(str)
    agg = df.groupby(["family", "point"]).agg(bytes_total=("bytes_total", "mean"), kl_x_noise=("kl_x_noise", gmean),
                                              kl_worst=("kl_x_noise", "max"), top1=("top1", "mean"),
                                              docs=("doc", "count")).reset_index()
    agg = agg[agg.family != "other"].sort_values(["family", "bytes_total"])
    save_table(agg.set_index(["family", "point"]), "stage5_budget_points", floatfmt=".3g")
    save_table(df.pivot_table(index=["family", "point"], columns="doc", values="kl_x_noise"),
               "stage5_budget_points_by_doc", floatfmt=".3g")
    return df, agg


def quest_decomp(grid="s5d"):
    """Why Quest as published is weaker at equal bytes on a GQA model: at Quest-2048's bytes, pages chosen per
    query head with layers 0-1 dense (as published) -> per KV head (softmax sum over the group; sink and newest
    blocks always in) with layers 0-1 dense -> the same with layer 0 dense only (stage 4's variant)."""
    df = summaries([grid], model="8b")
    if df.empty:
        return None
    label = {"questp2048": "as published: own pages per query head, layers 0-1 dense",
             "quest16softnative_match-questp2048_dl01": "pages per KV head, layers 0-1 dense",
             "quest16softnative_match-questp2048": "pages per KV head, layer 0 dense (stage 4's variant)"}
    df = df[df.condition.isin(label)]
    t = df.pivot_table(index="condition", columns="doc", values="kl_x_noise").reindex(list(label))
    t["geometric mean"] = [gmean(r) for r in t.values]
    t["bytes"] = df.groupby("condition").bytes_total.mean().reindex(list(label)).values
    t["top1"] = df.groupby("condition").top1.mean().reindex(list(label)).values
    t.index = [label[c] for c in t.index]
    save_table(t, "stage5_quest_decomp", floatfmt=".3g")
    return t


def budget_fixed(df, budgets=(0.2, 0.3, 0.45, 0.64), fams=("refresh", "questp", "topk", "quest_s4best")):
    rows = []
    for fam in fams:
        for B in budgets:
            vals = np.array([interp_at(d.bytes_total.values, d.kl_x_noise.values, B)
                             for _, d in df[df.family == fam].groupby("doc")], dtype=float)
            rows.append({"family": fam, "bytes": B, "kl_x_noise": gmean(vals),
                         "kl_worst": np.nanmax(vals) if np.isfinite(vals).any() else np.nan,
                         "docs": int(np.isfinite(vals).sum())})
    r = pd.DataFrame(rows)
    r["cell"] = [f"{k:.3g} ({n})" if n else "-" for k, n in zip(r.kl_x_noise, r.docs)]
    t = r.pivot(index="bytes", columns="family", values="cell").sort_index(ascending=False)[list(fams)]
    save_table(t, "stage5_budget_fixed")             # cell: geometric mean over the documents in range (count)
    return r


